# -*- coding: utf-8 -*-
"""**显示层断句**：给没有标点的连排正文加句读（「，」），让人读得下去（viewer 专用）。

为什么要它
----------
《洪武正韻》《字鑒》《玉篇》这类书的正文是一个【】包到底的连排：
「道【周礼注先王所以敎道民者音徒报切礼记王人延客祭郑康成曰延道也…】」，
一百七十个字连成一块。用户给的判据是**分类清不清**：注、音、注交替着读就清楚。

**为什么不是「逐词加空格」**：第一版这么做过，结果「月在甲曰毕在乙曰橘」被切成
「月 在 甲 曰 毕 在 乙 曰 橘」——每字一停，比不分还难读。字书正文的停顿在**句读**上，
不在词上；用户要的也是「月在甲曰毕，在乙曰橘」。

判据（句读的老办法 + 这批书的固定句式）
----------------------------------------
1. **起句词前断**：`本亦作 一曰 又 凡 如 与 从 象形 指事 會意 形聲 本作 俗作
   亦作 今作 籀文 古文 篆文 隷作 按 案`——
   这些词在**条目式**正文（有【】的字书/韵书）里几乎总是新一句的起头；
2. **收句词后断**：`也 矣 焉 哉 乎`（后面紧跟标点的不重复加）；
3. **`在X曰Y` 整组之后断**（月令串的固定句式），不在「在」前断——见 `_ZAIYUE`；
4. **反切整体不拆**（`音徒报切` 是一个单位），`【】` 紧贴；
5. 已经带标点的正文**原样返回**——那是作者/整理者自己的标点，不该覆盖。

**两套起句词表**（`_BREAK_BEFORE` / `_BREAK_BEFORE_PROSE`）：条目式正文
（一个条目里「一曰…又…从某从某」并列）用全表；**散句**（徐锴按语这类连贯注文，
正文里没有【】）用窄表，去掉 `凡 如 与 从`——那些字在散文里多是句中的动词，
不是句子的起头（实测切出「帝居福，从衣非此字」「华实，如山茱茰」）。

**几处硬护栏**（都是实测切错之后加的，切错的原样留在注释里）：
`_CING_GUARD`（`皆从/故或从/以为从` 不断）、`_XIANG_GUARD`（`故皆象形` 不断）、
`_AN_GUARD`（`臣锴按/又按/今按` 不断）、`又` 后面紧跟另一个起句词时不断、
断点前不足 2 字不断（「丂，古文…」）、收句词占满整句时不断（「焉，鸟黄色」）。

**这是显示层**：`data/` 一条不改，也不声称原文有这些句读。原文一条仍是那一条；
断错了只影响看着别扭，不影响任何结论。下游要原文，读 `data/`，不要读这个页面。

为什么不引外部规则：本机此刻网络不通（GitHub 也推不上去），没取到网页；
规则取自句读的通行做法（起句虚词前断、收句语气词后断）与这批书的固定句式，
上面第 1、2 条就是全部依据，可逐条对着例子验。
"""
from __future__ import annotations

import re

# 句读之前的起句词（长的写前面：startswith 按顺序匹配）。
#
# ⚠ 只收**几乎总是新一句起头**的词。第一版把 `音 作 同 或 谓 云 而 亦 皆 即 则`
# 也收进来，结果「说文作」「三字不同」「在己曰则」全被切开——这些字在词里出现得更频繁。
# 宁可少断，不可乱断。
_BREAK_BEFORE = (
    "本亦作", "一曰", "本作", "俗作", "亦作", "今作", "籀文", "古文", "篆文",
    "隷作", "隶作", "象形", "指事", "會意", "会意", "形聲", "形声", "凡", "如",
    "與", "与", "从", "從", "又", "按", "案",
)
# 「散句」用的窄表（正文里没有【】时启用）：去掉 `凡 如 與 与 从 從`。
#
# ⚠ 为什么分两套：`【】` 是字书/韵书的**条目式**正文（一个条目里
# 「一曰…又…从某从某…」并列），`从/凡/如/与` 在那里确实是新一句的起头；
# 而**散句**（徐锴按语这类注文）是连贯散文，`从` 常是句子中间的动词——
# 实测切出「又西都赋曰仰福帝居福，从衣非此字」「华实，如山茱茰」，
# 都不是断句，是劈词。散句里只留「一句的开头」最稳的那几个词。
_BREAK_BEFORE_PROSE = (
    "本亦作", "一曰", "本作", "俗作", "亦作", "今作", "籀文", "古文", "篆文",
    "隷作", "隶作", "象形", "指事", "會意", "会意", "形聲", "形声", "又", "按", "案",
)
# 句读之后的收句词
_BREAK_AFTER = set("也矣焉哉乎")

# 「在甲曰毕」这一族句式：**在它整组之后**断，而不是在「在」前断。
#
# ⚠ 第一版把「在」当起句词（在「在」**前面**加「，」），实测两处切错：
#   ① 「尔雅岁在甲曰阏逢」→「尔雅岁，在甲曰阏逢」——「岁在甲曰阏逢」是一个判断句，
#      「岁」与「在」之间不能断；
#   ② 「月在甲曰毕」→「月，在甲曰毕」——同理。
# 所以断点改到「在X曰Y」**之后**。
#
# ⚠ 但「Y 之后」不能无条件断：`岁在甲曰阏逢` 的 Y 是「阏」，后面紧跟「逢」——
# 「阏逢」是**一个词**（岁阳名），在中间加「，」就把它劈了（实测切出「阏，逢月」）。
# 判据是**series 的形状**：月令串里每个「在X曰Y」后面紧跟的正是下一个「在」，
# 所以只在 `Y 后面是「在」`时断；其余一律不断（宁可少断，不可劈词）。
_ZAIYUE = re.compile(
    r"在[\u3400-\u4dbf\u4e00-\u9fff]曰[\u3400-\u4dbf\u4e00-\u9fff](?=在)")

# 反切：上字 + 下字 + 切/反（3 字），前面可能带「音」
_FQ = re.compile(r"(?:音)?[\u3400-\u4dbf\u4e00-\u9fff\U00020000-\U0002a6df]{2}[切反]")

# 这些字符前面不加「，」（已经是标点/括号/换行）
_NO_BEFORE = set("，。、；：？！【】（）「」『』《》\n\x01")
# 断点之后紧跟这些字符时不补「，」（【】 要紧贴，不能写成「…极，【塞先北反】」）
_NO_AFTER = set("，。、；：？！【】（）「」『』《》\n\x01")

_MIN = 2          # 上一处「，」以来不足这么多字就不再断（避免「丂，古文」这种一字一段）

# 「故皆象形焉」「皆形聲」这类构形说明前面是副词时，`象形` 不是新一句的起头
_XIANG_GUARD = frozenset(("象形", "指事", "會意", "会意", "形聲", "形声"))

# 「皆从月」「亦从某」「故从示」「或从米」这类：前面是这个字时，`从` 不是新一句的起头
# （实测系傳注文：「祭神之精米也，故或，从米」——`故或从米` 是通的，切开就断了）
_CING_GUARD = set("皆亦悉咸俱故或而則则即乃因各且若为爲")

# 「臣锴按」「又按」「今按」：`按/案` 是接上去的动词，不另起一句
# （实测「臣锴，按此字…」「又，按前汉…」「今，按决明药菜也」——把主语/时间词与按语切成两截）
_AN_GUARD = set("又亦故而再锴愚臣慎今")


# 已经有标点的正文不再加句读：分词/断句是给「没有标点的连排」用的。
_PUNCT = "。，、；：？！"


def _already_punctuated(text: str) -> bool:
    n = sum(text.count(c) for c in _PUNCT)
    return n >= max(3, len(text) // 40)


def _protect(text: str) -> str:
    return _FQ.sub(lambda m: "\x01" + m.group(0) + "\x01", text)


def punctuate(text: str) -> str:
    """给连排正文加句读；返回带「，」的正文（原文其余字符一个不改）。"""
    if not text:
        return text
    if len(text) < 12:                     # 短条本来就好读，不加
        return text
    if _already_punctuated(text):
        return text
    s = _protect(text)
    # 条目式（有【】）用全表；散句（注文）用窄表——见 _BREAK_BEFORE_PROSE 的说明
    before = _BREAK_BEFORE if "【" in text else _BREAK_BEFORE_PROSE
    after_zaiyue = {m.end() for m in _ZAIYUE.finditer(s)}
    out: list[str] = []
    seg = 0                                # 上一处「，」以来已经攒了几个字
    i, n = 0, len(s)
    while i < n:
        ch = s[i]
        if ch == "\x01":                   # 反切断整体照抄
            j = s.index("\x01", i + 1)
            out.append(s[i:j + 1])
            seg += j + 1 - i
            i = j + 1
            continue
        hit = next((w for w in before if s.startswith(w, i)), None)
        if hit is not None:
            prev = out[-1][-1] if out else ""
            # 「音与导同」是一个判断句（音 = 与导同），不能在「与」前断
            if hit in ("与", "與") and out and out[-1].endswith("音"):
                hit = None
            # 「凡月之属皆从月」：`皆从` 是连着的，断成「皆，从月」读不通
            elif hit in ("从", "從") and prev in _CING_GUARD:
                hit = None
            # 「故皆象形焉」同理：`皆象形` 不能切开
            elif hit in _XIANG_GUARD and prev in _CING_GUARD:
                hit = None
            # 「臣锴按」「又按」：说话人与按语不能切成两截
            elif hit in ("按", "案") and prev in _AN_GUARD:
                hit = None
            # 「臣又按」「锴又按」：`臣又` 是主语接副词，不能断成「臣，又按」
            elif hit == "又" and prev in _AN_GUARD:
                hit = None
            # 「此又古文视字」：`又` 后面紧跟另一个起句词时，让后一个词去断，
            # 否则会切出「此，又，古文…」这种一字一段
            elif hit == "又" and any(s.startswith(w, i + 1) for w in before):
                hit = None
            # 断点前的这一句不足 2 字就不再断（「丂，古文…」这种把字头单独切出来）
            elif seg < _MIN or not out or prev in _NO_BEFORE:
                hit = None
            else:
                out.append("，")
                seg = 0
        # 起句词本身整段照抄（避免「凡」匹配完又把「如」拆出来）
        w = hit or ch
        out.append(w)
        seg += len(w)
        i += len(w)
        if w[-1] in _BREAK_AFTER or i in after_zaiyue:
            nxt = s[i] if i < n else ""
            # 收句词本身占满整句时不断（「焉，鸟黄色…」——「焉」是字头，
            # 「焉鸟」是一个鸟名，切断就变成「焉」单独一个字）
            if nxt and nxt not in _NO_AFTER and seg > len(w):
                out.append("，")
                seg = 0
    return re.sub(r"，{2,}", "，", "".join(out).replace("\x01", ""))


# 兼容旧调用点（build_viewer 曾用 wordize 这个名字）
wordize = punctuate


